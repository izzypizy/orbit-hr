import { Injectable, NotFoundException } from '@nestjs/common';
import { AuthUser } from '../common/auth';
import { createMockData } from './mock-data';
import { Payslip, ReceiptFile } from './types';

/**
 * In-memory data store loaded with mock data. Data resets when the API restarts.
 * To move to a real database, replace this class with a repository backed by Prisma/TypeORM.
 */
@Injectable()
export class MockDb {
  private readonly data = createMockData();

  readonly departments = this.data.departments;
  readonly employees = this.data.employees;
  readonly leaveTypes = this.data.leaveTypes;
  readonly leaveBalances = this.data.leaveBalances;
  readonly leaveRequests = this.data.leaveRequests;
  readonly claimCategories = this.data.claimCategories;
  readonly claims = this.data.claims;
  readonly claimItems = this.data.claimItems;
  readonly receipts = new Map<number, ReceiptFile>(); // keyed by claim item id
  readonly attendance = this.data.attendance;
  readonly overtimeRequests = this.data.overtimeRequests;
  readonly payslips: Payslip[] = []; // generated by PayrollService on startup
  readonly checklists = this.data.checklists;
  readonly reviews = this.data.reviews;
  readonly trainings = this.data.trainings;
  announcements = this.data.announcements;
  holidays = this.data.holidays;

  employee(id: number) {
    const e = this.employees.find((x) => x.id === id);
    if (!e) throw new NotFoundException('Employee not found');
    return e;
  }

  department(id: number) {
    return this.departments.find((x) => x.id === id)!;
  }

  /** Employee fields safe to return to the client (no password hash or salary). */
  employeeView(id: number | null) {
    if (id == null) return null;
    const { passwordHash, basicSalary, ...rest } = this.employee(id);
    return { ...rest, department: this.department(rest.departmentId).name, manager: rest.managerId ? this.employee(rest.managerId).name : null };
  }

  isManagerOf(managerId: number, employeeId: number) {
    return this.employee(employeeId).managerId === managerId;
  }

  /** HR sees everyone, managers see their direct reports, everyone sees themselves. */
  canSeeEmployee(user: AuthUser, employeeId: number) {
    return user.role === 'HR' || user.id === employeeId || this.isManagerOf(user.id, employeeId);
  }
}
